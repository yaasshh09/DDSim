from __future__ import annotations
import math
from functools import cache
from pathlib import Path
import numpy as np
from ddsim.device.builder import build_device
from ddsim.device.doping import abrupt_junction
from ddsim.device.transport import TransportModels
from ddsim.discretize.boundary import OhmicPlate
from ddsim.extract.iv import IVCurve, gate_sweep
from ddsim.mesh.gmsh import read_msh_volume
from tests.regression.devsim_gen import parameters as P
from tests.regression.devsim_gen import write_diode3d_mesh as W

ROOT = Path(__file__).resolve().parents[2]
MESH = ROOT / "data" / "golden" / "diode3d_gmsh.msh"
GOLDEN = ROOT / "data" / "golden" / "diode3d_gmsh.csv"
B = P.DIODE3D_BENCHMARK


def test_the_shared_mesh_is_ddsims_own_split_box() -> None:
    m = W.mesh()
    g = read_msh_volume(MESH)
    np.testing.assert_array_equal(g.points, np.column_stack([m.node_x, m.node_y, m.node_z]))
    assert sorted(map(tuple, g.tets.tolist())) == sorted(map(tuple, m.tets.tolist()))
    assert g.contact_nodes("anode") == tuple(np.flatnonzero(W.anode(m)).tolist())
    assert g.contact_nodes("cathode") == tuple(np.flatnonzero(W.cathode(m)).tolist())


def test_golden_header_records_its_provenance() -> None:
    text = GOLDEN.read_text(encoding="utf-8")
    assert "generated by: tests/regression/devsim_gen/generate_diode3d.py" in text
    assert "mesh file: data/golden/diode3d_gmsh.msh" in text
    assert "MKL_NUM_THREADS=1" in text
    assert f"tolerance: {B.tolerance}" in text


def golden() -> list[tuple[float, float]]:
    rows = [line.split(",") for line in GOLDEN.read_text(encoding="utf-8").splitlines() if line and not line.startswith("#") and not line.startswith("voltage")]
    return [(float(r[0]), float(r[2])) for r in rows]


@cache
def ours() -> IVCurve:
    g = read_msh_volume(MESH)
    d = build_device(mesh=g.mesh(), doping=abrupt_junction(Na=B.Na, Nd=B.Nd, position=B.junction), contacts=(OhmicPlate(name="anode", nodes=g.contact_nodes("anode"), voltage=0.0), OhmicPlate(name="cathode", nodes=g.contact_nodes("cathode"), voltage=0.0)))
    return gate_sweep(d, [v for v, _ in golden()], contact="anode", measure_at="cathode", models=TransportModels.for_device(d))


def test_the_cathode_current_on_the_shared_mesh_matches_devsim(record_property) -> None:
    c = ours()
    assert c.complete, c.message
    want = golden()
    assert [p.voltage for p in c.points] == [v for v, _ in want]
    err = [abs(math.log(p.current / w)) for p, (_, w) in zip(c.points, want, strict=True)]
    record_property("worst_log_error", max(err))
    bad = [f"V {v:+.2f}: devsim {w:.6e}, ddsim {p.current:.6e} A" for p, (v, w), e in zip(c.points, want, err, strict=True) if e > B.tolerance]
    assert not bad, "\n".join(bad)
