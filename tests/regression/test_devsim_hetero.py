from __future__ import annotations
import json
from functools import cache
from pathlib import Path
import numpy as np
from ddsim.device.transport import TransportModels
from ddsim.extract.iv import IVCurve, gate_sweep
from tests.regression.devsim_gen import parameters as P
from tests.regression.devsim_gen.write_hetero_inputs import diode, inputs

ROOT = Path(__file__).resolve().parents[2]
GOLDEN = ROOT / "data" / "golden" / f"{P.HETERO_NAME}.csv"
INPUTS = ROOT / "data" / "golden" / f"{P.HETERO_NAME}_inputs.json"


def test_the_inputs_file_is_what_ddsim_writes_today() -> None:
    saved = json.loads(INPUTS.read_text(encoding="utf-8"))
    fresh = inputs()
    assert saved.keys() == fresh.keys()
    for k in saved:
        np.testing.assert_allclose(saved[k], fresh[k], rtol=1e-12, atol=0, err_msg=k)


def test_golden_header_records_its_provenance() -> None:
    text = GOLDEN.read_text(encoding="utf-8")
    assert "generated by: tests/regression/devsim_gen/generate_hetero.py" in text
    assert f"tolerance: {P.HETERO_TOLERANCE}" in text
    assert f"nodes: {P.HETERO_N_NODES}" in text


def golden() -> list[np.ndarray]:
    rows = [line.split(",") for line in GOLDEN.read_text(encoding="utf-8").splitlines() if line and not line.startswith(("#", "voltage"))]
    return [np.array([float(r[k]) for r in rows]) for k in range(3)]


@cache
def ours() -> IVCurve:
    d = diode()
    return gate_sweep(d, list(golden()[0]), contact="anode", measure_at="anode", models=TransportModels.for_device(d))


def test_the_heterojunction_current_matches_devsim(record_property) -> None:
    c = ours()
    assert c.complete, c.message
    v, anode, cathode = golden()
    assert [p.voltage for p in c.points] == list(v)
    got = np.array([p.current for p in c.points])
    err = np.abs(got / anode - 1.0)
    allowed = np.maximum(P.HETERO_TOLERANCE, 3.0 * np.abs(anode + cathode) / np.abs(anode))
    record_property("worst_relative_error", float(err.max()))
    bad = [f"V {a:+.2f}: devsim {w:.10e}, ddsim {g:.10e}, off {e:.2e} against {t:.2e}" for a, w, g, e, t in zip(v, anode, got, err, allowed, strict=True) if e > t]
    assert not bad, "\n".join(bad)
