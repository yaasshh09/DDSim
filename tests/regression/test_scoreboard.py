def _case(device: str ='pn_diode',** knobs:float) -> Any :

    Defaults ={"pn_diode":{},"mos_cap":{},"nmos":{'L_gate' :1e-4}}[device]
    return  tool.Case (  "x001", device, {  **  Defaults ,   **  knobs }, 0 )


