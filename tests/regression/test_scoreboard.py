"""Tier 5: the scoreboard against DEVSIM.

phases/PHASE-8.md. Tiers 1 to 4 ask whether ddsim is right. This one asks
whether it is better than DEVSIM, and it only reads numbers that were measured:
the CSVs in `data/scoreboard/`, generated by hand by `tools/scoreboard.py` and
`devsim_gen/scoreboard.py`, the same way the golden data is.

The capability matrix: every "yes" in it has to point at something that
exists, a test for ddsim, and for DEVSIM either a name in the snapshot of its
API or a function in the generators that scripts it. A row whose evidence goes
missing fails here, which is what stops a capability quietly turning into a
sentence in a README.

The robustness case set: it has to be exactly the seeded draw from the knob
ranges the constructors declare today. If a range moves, the draw moves, and
this fails until the cases are regenerated on purpose and the robustness
results with them.
"""

