from __future__ import annotations
import json
from functools import cache
from pathlib import Path
import numpy as np
from ddsim.device.density_gradient import DensityGradient, solve_density_gradient
from tests.regression.devsim_gen import parameters as P
from tests.regression.devsim_gen.write_dg_inputs import capacitor, inputs

ROOT = Path(__file__).resolve().parents[2]
GOLDEN = ROOT / "data" / "golden" / f"{P.DG_NAME}.csv"
INPUTS = ROOT / "data" / "golden" / f"{P.DG_NAME}_inputs.json"


def test_the_benchmark_mirrors_ddsims_density_gradient() -> None:
    m = DensityGradient(gamma=P.DG_GAMMA)
    assert (m.gamma_ox, m.mass, m.mass_ox, m.barrier, m.mass_tunnel) == (P.DG_GAMMA_OX, P.DG_MASS, P.DG_MASS_OX, P.DG_BARRIER, P.DG_MASS_TUNNEL)


def test_the_inputs_file_is_what_ddsim_writes_today() -> None:
    saved = json.loads(INPUTS.read_text(encoding="utf-8"))
    fresh = inputs()
    assert saved.keys() == fresh.keys()
    for k in saved:
        np.testing.assert_allclose(saved[k], fresh[k], rtol=1e-12, atol=0, err_msg=k)


def test_golden_header_records_its_provenance() -> None:
    text = GOLDEN.read_text(encoding="utf-8")
    assert "generated by: tests/regression/devsim_gen/generate_dg.py" in text
    assert f"gamma: {P.DG_GAMMA}" in text
    assert f"tolerance: {P.DG_TOLERANCE}" in text


def golden() -> tuple[np.ndarray, np.ndarray]:
    rows = [line.split(",") for line in GOLDEN.read_text(encoding="utf-8").splitlines() if line and not line.startswith(("#", "gate"))]
    return np.array([float(r[0]) for r in rows]), np.array([float(r[1]) for r in rows])


@cache
def ours() -> np.ndarray:
    return np.array([solve_density_gradient(capacitor(v), DensityGradient(gamma=P.DG_GAMMA)).sheet_charge for v in P.DG_GATES])


def test_the_sheet_charge_matches_devsim(record_property) -> None:
    v, want = golden()
    assert tuple(v) == P.DG_GATES
    err = np.abs(ours() / want - 1.0)
    record_property("worst_charge_error", float(err.max()))
    assert err.max() < P.DG_TOLERANCE, f"worst {err.max():.3e} at {v[int(err.argmax())]:+.2f} V"


def test_the_capacitance_matches_devsim(record_property) -> None:
    v, want = golden()
    c_dev = -np.gradient(want, v)
    c_ours = -np.gradient(ours(), v)
    err = np.abs(c_ours / c_dev - 1.0)
    record_property("worst_capacitance_error", float(err.max()))
    assert err.max() < P.DG_TOLERANCE, f"worst {err.max():.3e} at {v[int(err.argmax())]:+.2f} V"
