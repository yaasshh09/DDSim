from __future__ import annotations
import math
from functools import cache
from pathlib import Path
import numpy as np
import pytest
from ddsim.device.builder import Device, build_device
from ddsim.device.regions import OXIDE, SILICON, triangle_regions
from ddsim.device.transport import TransportModels
from ddsim.discretize.boundary import GateContact, OhmicPlate
from ddsim.extract.iv import IVCurve, gate_sweep
from ddsim.mesh.gmsh import read_msh
from ddsim.mesh.trimesh import triangulated
from tests.regression.devsim_gen import parameters as P
from tests.regression.devsim_gen.write_nmos_mesh import device as tensor_device

ROOT = Path(__file__).resolve().parents[2]
MESH = ROOT / "data" / "golden" / "nmos_1um_gmsh.msh"
GOLDEN = ROOT / "data" / "golden" / "nmos_1um_gmsh.csv"
B = P.GMSH_BENCHMARK


def test_the_shared_mesh_is_ddsims_own_triangulation() -> None:
    d = tensor_device()
    g = read_msh(MESH)
    m = triangulated(d.mesh)
    np.testing.assert_array_equal(g.points, np.column_stack([m.node_x, m.node_y]))
    assert sorted(map(tuple, g.triangles.tolist())) == sorted(map(tuple, m.triangles.tolist()))
    for c in d.contacts:
        assert g.contact_nodes(c.name) == tuple(sorted(c.nodes)), c.name


def test_golden_header_records_its_provenance() -> None:
    text = GOLDEN.read_text(encoding="utf-8")
    assert "generated by: tests/regression/devsim_gen/generate_nmos_gmsh.py" in text
    assert "mesh file: data/golden/nmos_1um_gmsh.msh" in text
    assert f"tolerance: {B.tolerance}" in text


def built(drain: float) -> Device:
    t = tensor_device()
    g = read_msh(MESH)
    m = g.mesh()
    material = np.array([SILICON if r == "bulk" else OXIDE for r in g.region_of_triangles])
    gate = next(c for c in t.contacts if isinstance(c, GateContact))
    contacts = tuple(OhmicPlate(name=n, nodes=g.contact_nodes(n), voltage=drain if n == "drain" else 0.0) for n in ("source", "drain", "body")) + (GateContact(name="gate", nodes=g.contact_nodes("gate"), voltage=0.0, work_function=gate.work_function),)
    return build_device(mesh=m, doping=t.doping, contacts=contacts, regions=triangle_regions(m, material))


@cache
def ours(drain: float) -> IVCurve:
    d = built(drain)
    return gate_sweep(d, list(B.gate_voltages), models=TransportModels.for_device(d, mobility="constant"))


def golden() -> dict[str, list[float]]:
    rows = [line.split(",") for line in GOLDEN.read_text(encoding="utf-8").splitlines() if line and not line.startswith("#") and not line.startswith("gate")]
    return {"gate": [float(r[0]) for r in rows], "low": [float(r[1]) for r in rows], "high": [float(r[3]) for r in rows]}


@pytest.mark.parametrize("high", [False, True], ids=["Vd_low", "Vd_high"])
def test_the_drain_current_on_the_shared_mesh_matches_devsim(high: bool) -> None:
    g = golden()
    c = ours(B.drain_high if high else B.drain_low)
    assert c.complete, c.message
    want = g["high" if high else "low"]
    bad = [f"Vg {v:+.2f} V: devsim {w:.6e}, ddsim {i:.6e} A/cm" for v, w, i in zip(g["gate"], want, c.current, strict=True) if abs(math.log(i / w)) > B.tolerance]
    assert not bad, "\n".join(bad)
