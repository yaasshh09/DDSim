from __future__ import annotations
import argparse
import os
import sys
import time
from typing import Any

for _name in ("MKL_NUM_THREADS", "OMP_NUM_THREADS"):
    os.environ[_name] = "1"

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..")))

import math

import generate_diodes as G
import parameters as P
from devsim import add_gmsh_contact, add_gmsh_region, create_device, create_gmsh_mesh, delete_device, delete_mesh, finalize_mesh, get_node_model_values, set_parameter, solve

from ddsim.mesh.msh41 import parse_volume

MESH = os.path.join("data", "golden", "diode3d_gmsh.msh")
DEVSIM_TRIANGLE = 2
DEVSIM_TETRAHEDRON = 3
RELATIVE_ERROR = 1e-10


def load(device: str, path: str) -> None:
    xyz, tet, region, tri, contact = parse_volume(open(path, encoding="utf-8").read(), path)
    names = sorted(set(region) | set(contact))
    coordinates = [v for p in xyz for v in p]
    elements: list[float] = []
    for t, r in zip(tet, region, strict=True):
        elements += [DEVSIM_TETRAHEDRON, names.index(r), *t]
    for f, c in zip(tri, contact, strict=True):
        elements += [DEVSIM_TRIANGLE, names.index(c), *f]
    create_gmsh_mesh(mesh=device, coordinates=coordinates, elements=elements, physical_names=names)
    add_gmsh_region(gmsh_name=G.REGION, mesh=device, region=G.REGION, material="Silicon")
    for c in (G.ANODE, G.CATHODE):
        add_gmsh_contact(gmsh_name=c, mesh=device, name=c, region=G.REGION, material="metal")
    finalize_mesh(mesh=device)
    create_device(mesh=device, device=device)


def check_equilibrium(b: P.DiodeBenchmark, device: str) -> float:
    psi = get_node_model_values(device=device, region=G.REGION, name="Potential")
    x = get_node_model_values(device=device, region=G.REGION, name="x")
    want_p, want_n = -P.V_T * math.log(b.Na / P.N_I), P.V_T * math.log(b.Nd / P.N_I)
    worst = max([abs(v - want_p) for v, at in zip(psi, x, strict=True) if at < b.junction / 3] + [abs(v - want_n) for v, at in zip(psi, x, strict=True) if at > 0.9 * b.length])
    if worst > 1e-3:
        raise RuntimeError(f"devsim's equilibrium potential is {worst:.3e} V off the neutral bulk values, so its 3D solve has returned a wrong state it calls converged. Check MKL_NUM_THREADS.")
    return worst


def sweep(b: P.DiodeBenchmark, path: str) -> tuple[list[dict[str, Any]], int]:
    d = b.name
    load(d, path)
    G.set_doping(b, d)
    G.set_silicon_parameters(d, b.T)
    G.build_physics(d)
    print(f"    equilibrium within {check_equilibrium(b, d):.3e} V of the neutral bulk", flush=True)
    rows: list[dict[str, Any]] = []
    a = 0.0
    for v in sorted(b.voltages):
        while a < v - 1e-12:
            a = min(v, round(a + 0.05, 10))
            set_parameter(device=d, name=f"{G.ANODE}_bias", value=a)
            solve(type="dc", absolute_error=1e10, relative_error=RELATIVE_ERROR, maximum_iterations=200, maximum_divergence=200)
        i, k = G.anode_current(d), G.cathode_current(d)
        rows.append({"voltage": v, "current": i, "cathode": k})
        print(f"    V={v:+.3f}  anode {i:+.6e} A  cathode {k:+.6e} A", flush=True)
    n = len(get_node_model_values(device=d, region=G.REGION, name="NetDoping"))
    delete_device(device=d)
    delete_mesh(mesh=d)
    return rows, n


def main() -> int:
    a = argparse.ArgumentParser(description="Generate benchmark 19, the 3D p+n diode on the shared tetrahedral mesh, with DEVSIM.")
    a.add_argument("--mesh", default=MESH)
    a.add_argument("--out", default=os.path.join("data", "golden"))
    o = a.parse_args()
    b = P.DIODE3D_BENCHMARK
    t = time.perf_counter()
    rows, n = sweep(b, o.mesh)
    took = time.perf_counter() - t
    p = os.path.join(o.out, f"{b.name}.csv")
    G.write_csv(b, rows, None, p)
    with open(p, encoding="utf-8") as f:
        text = f.read()
    text = text.replace("generated by: tests/regression/devsim_gen/generate_diodes.py", "generated by: tests/regression/devsim_gen/generate_diode3d.py")
    text = text.replace("# notes:", f"# mesh file: {o.mesh.replace(os.sep, '/')}\n# nodes: {n}\n# devsim wall time: {took:.1f} s\n# notes:", 1)
    text = text.replace("anode current [A/cm^2], cathode current [A/cm^2]", "anode current [A], cathode current [A]")
    text = "\n".join(line for line in text.split("\n") if not line.startswith(("# devsim h_junction", "# devsim h_bulk")))
    text = text.replace("# notes:", f"# devsim solve: MKL_NUM_THREADS=1, relative error {RELATIVE_ERROR:g}\n# notes:", 1)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"[{b.name}] wrote {p}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
