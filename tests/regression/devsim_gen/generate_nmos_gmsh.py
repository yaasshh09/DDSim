from __future__ import annotations
import argparse
import os
import sys
from typing import Any

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import generate_mosfet as G
from devsim import add_gmsh_contact, add_gmsh_interface, add_gmsh_region, create_device, create_gmsh_mesh, delete_device, delete_mesh, finalize_mesh

from ddsim.mesh.msh41 import LINE, TRIANGLE, parse
from tests.regression.devsim_gen import parameters as P

MESH = os.path.join("data", "golden", "nmos_1um_gmsh.msh")


def load(device: str, path: str) -> None:
    xy, tri, region, seg, contact = parse(open(path, encoding="utf-8").read(), path)
    names = sorted(set(region) | set(contact))
    coordinates = [v for x, y in xy for v in (x, y, 0.0)]
    elements: list[float] = []
    for t, r in zip(tri, region, strict=True):
        elements += [TRIANGLE, names.index(r), *t]
    for s, c in zip(seg, contact, strict=True):
        elements += [LINE, names.index(c), *s]
    create_gmsh_mesh(mesh=device, coordinates=coordinates, elements=elements, physical_names=names)
    add_gmsh_region(gmsh_name=G.BULK, mesh=device, region=G.BULK, material="Silicon")
    add_gmsh_region(gmsh_name=G.OXIDE, mesh=device, region=G.OXIDE, material="Oxide")
    for c in (G.SOURCE, G.DRAIN, G.BODY):
        add_gmsh_contact(gmsh_name=c, mesh=device, name=c, region=G.BULK, material="metal")
    add_gmsh_contact(gmsh_name=G.GATE, mesh=device, name=G.GATE, region=G.OXIDE, material="metal")
    add_gmsh_interface(gmsh_name="si_ox", mesh=device, name="si_ox", region0=G.BULK, region1=G.OXIDE)
    finalize_mesh(mesh=device)
    create_device(mesh=device, device=device)


def transfer_curve(b: P.MosfetBenchmark, drain: float, path: str) -> tuple[list[dict[str, Any]], int]:
    d = f"{b.name}_{drain:g}".replace(".", "_")
    with G.quiet():
        load(d, path)
    G.set_material_parameters(d)
    G.set_doping(b, d)
    with G.quiet():
        G.build_physics(d, b.gate_voltages[0], drain, b.models)
    rows: list[dict[str, Any]] = []
    for v in b.gate_voltages:
        G.ramp_to(d, G.GATE, G.gate_potential(v))
        with G.quiet():
            G.settle(d, balance_tol=G.BALANCE_TOL)
        rows.append({"gate": v, "drain": G.terminal_current(d, G.DRAIN), "source": G.terminal_current(d, G.SOURCE), "body": G.terminal_current(d, G.BODY)})
        print(f"    Vg={v:+.3f} V  Id={rows[-1]['drain']:+.6e} A/cm", flush=True)
    n = G.node_count(d)
    delete_device(device=d)
    delete_mesh(mesh=d)
    return rows, n


def main() -> int:
    a = argparse.ArgumentParser(description="Generate benchmark 18, the 1 um nmos on the shared Gmsh mesh, with DEVSIM.")
    a.add_argument("--mesh", default=MESH)
    a.add_argument("--out", default=os.path.join("data", "golden"))
    o = a.parse_args()
    b = P.GMSH_BENCHMARK
    print(f"[{b.name}] Vd = {b.drain_low} V", flush=True)
    low, n = transfer_curve(b, b.drain_low, o.mesh)
    print(f"[{b.name}] Vd = {b.drain_high} V", flush=True)
    high, _ = transfer_curve(b, b.drain_high, o.mesh)
    p = os.path.join(o.out, f"{b.name}.csv")
    G.write_csv(b, low, high, n, None, p)
    with open(p, encoding="utf-8") as f:
        text = f.read().replace("generated by: tests/regression/devsim_gen/generate_mosfet.py", "generated by: tests/regression/devsim_gen/generate_nmos_gmsh.py")
    text = text.replace("# notes:", f"# mesh file: {o.mesh.replace(os.sep, '/')}\n# notes:", 1)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"[{b.name}] wrote {p}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
