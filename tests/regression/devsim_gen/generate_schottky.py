from __future__ import annotations
import argparse
import datetime
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import parameters as P
from devsim import add_1d_contact, add_1d_mesh_line, add_1d_region, contact_equation, create_1d_mesh, create_device, delete_device, delete_mesh, finalize_mesh, get_contact_current, node_model, set_node_values, set_parameter, solve
from devsim.python_packages.model_create import CreateContactNodeModel, CreateSolution
from devsim.python_packages.simple_physics import CreateSiliconDriftDiffusion, CreateSiliconDriftDiffusionAtContact, CreateSiliconPotentialOnly, CreateSiliconPotentialOnlyContact, ece_name, hce_name
from generate_diodes import REGION, devsim_version, set_lifetimes, set_silicon_parameters

ANODE = "anode"
CATHODE = "cathode"


def constants(b: P.SchottkyBenchmark) -> dict[str, float]:
    n0 = P.NC * math.exp(-b.barrier / P.V_T)
    return {"vn": P.A_STAR_N * P.T * P.T / (P.Q * P.NC), "vp": P.A_STAR_P * P.T * P.T / (P.Q * P.NV), "n0b": n0, "p0b": P.N_I * P.N_I / n0}


def settle(d: str) -> None:
    solve(type="dc", absolute_error=1e10, relative_error=1e-10, maximum_iterations=60)


def device(b: P.SchottkyBenchmark, refine: float) -> str:
    d = f"{b.name}_r{refine:g}".replace(".", "_")
    create_1d_mesh(mesh=d)
    add_1d_mesh_line(mesh=d, pos=0.0, ps=b.devsim_h_contact / refine, tag="top")
    add_1d_mesh_line(mesh=d, pos=b.length, ps=b.devsim_h_bulk / refine, ns=b.devsim_h_bulk / refine, tag="bot")
    add_1d_contact(mesh=d, name=ANODE, tag="top", material="metal")
    add_1d_contact(mesh=d, name=CATHODE, tag="bot", material="metal")
    add_1d_region(mesh=d, material="Silicon", region=REGION, tag1="top", tag2="bot")
    finalize_mesh(mesh=d)
    create_device(mesh=d, device=d)
    node_model(device=d, region=REGION, name="NetDoping", equation=f"{b.Nd:.16e}")
    set_silicon_parameters(d)
    for k, v in constants(b).items():
        set_parameter(device=d, region=REGION, name=k, value=v)

    CreateSolution(d, REGION, "Potential")
    CreateSiliconPotentialOnly(d, REGION)
    for c in (ANODE, CATHODE):
        set_parameter(device=d, name=f"{c}_bias", value=0.0)
    CreateSiliconPotentialOnlyContact(d, REGION, CATHODE)
    CreateContactNodeModel(d, ANODE, "schottky_potential", f"Potential - {ANODE}_bias - V_t*log(n0b/n_i)")
    CreateContactNodeModel(d, ANODE, "schottky_potential:Potential", "1")
    contact_equation(device=d, contact=ANODE, name="PotentialEquation", node_model="schottky_potential", edge_charge_model="contactcharge_edge")
    solve(type="dc", absolute_error=1.0, relative_error=1e-12, maximum_iterations=60)

    for m, e in (("Electrons", "IntrinsicElectrons"), ("Holes", "IntrinsicHoles")):
        CreateSolution(d, REGION, m)
        set_node_values(device=d, region=REGION, name=m, init_from=e)
    set_lifetimes(d)
    CreateSiliconDriftDiffusion(d, REGION, mu_n="mu_n", mu_p="mu_p")
    CreateSiliconDriftDiffusionAtContact(d, REGION, CATHODE)
    for name, v, c, c0, edge, eq in (("electrons", "vn", "Electrons", "n0b", "ElectronCurrent", ece_name), ("holes", "vp", "Holes", "p0b", "HoleCurrent", hce_name)):
        CreateContactNodeModel(d, ANODE, f"schottky_{name}", f"-ElectronCharge*{v}*({c} - {c0})/NodeVolume")
        CreateContactNodeModel(d, ANODE, f"schottky_{name}:{c}", f"-ElectronCharge*{v}/NodeVolume")
        contact_equation(device=d, contact=ANODE, name=eq, node_model=f"schottky_{name}", edge_model=edge, edge_current_model=edge)
    settle(d)
    return d


def current(d: str, contact: str) -> float:
    return get_contact_current(device=d, contact=contact, equation=ece_name) + get_contact_current(device=d, contact=contact, equation=hce_name)


def sweep(b: P.SchottkyBenchmark, refine: float) -> list[dict[str, float]]:
    d = device(b, refine)
    rows: dict[float, dict[str, float]] = {}
    for side in (sorted((v for v in b.voltages if v < 0.0), reverse=True), sorted(v for v in b.voltages if v > 0.0)):
        at = 0.0
        set_parameter(device=d, name=f"{ANODE}_bias", value=0.0)
        settle(d)
        for v in side:
            while abs(v - at) > 1e-12:
                at += max(-0.02, min(0.02, v - at))
                set_parameter(device=d, name=f"{ANODE}_bias", value=at)
                settle(d)
            rows[v] = {"voltage": v, "current": current(d, ANODE), "cathode": current(d, CATHODE)}
            print(f"    {v:+.2f} V: {rows[v]['current']:.6e} A/cm^2", file=sys.stderr, flush=True)
    delete_device(device=d)
    delete_mesh(mesh=d)
    return [rows[v] for v in sorted(rows)]


def write(b: P.SchottkyBenchmark, rows: list[dict[str, float]], mesh: float | None, path: str) -> None:
    k = constants(b)
    h = [
        f"# device: {b.name}",
        f"# benchmark: {b.number} in docs/04-validation.md",
        "# generated by: tests/regression/devsim_gen/generate_schottky.py",
        f"# generator: devsim {devsim_version()} on python {sys.version.split()[0]}",
        f"# generated on: {datetime.datetime.now(datetime.UTC).strftime('%Y-%m-%d')}",
        f"# tolerance: {b.tolerance}",
        f"# Nd: {b.Nd:.6e}",
        f"# length: {b.length:.6e}",
        f"# barrier: {b.barrier:.6e}",
        f"# vn: {k['vn']:.12e}",
        f"# vp: {k['vp']:.12e}",
        f"# n0b: {k['n0b']:.12e}",
        f"# devsim h_contact: {b.devsim_h_contact:.6e}",
        f"# devsim h_bulk: {b.devsim_h_bulk:.6e}",
        "# statistics: Boltzmann",
    ]
    if mesh is not None:
        h.append(f"# mesh convergence: {mesh:.3e} worst relative change in current when every spacing is halved")
    h.append("# notes: " + b.notes)
    h.append("# models: Boltzmann, constant mobility, SRH with Scharfetter lifetimes, thermionic emission anode, ohmic cathode")
    h.append("# columns: anode bias [V], anode current [A/cm^2], cathode current [A/cm^2]")
    h.append("voltage,current,cathode_current")
    h += [f"{r['voltage']:.10g},{r['current']:.12e},{r['cathode']:.12e}" for r in rows]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(h) + "\n")


def main() -> int:
    a = argparse.ArgumentParser(description="Generate the Schottky diode golden curve with DEVSIM.")
    a.add_argument("--out", default=os.path.join("data", "golden"), help="output directory for the CSV files")
    a.add_argument("--no-mesh-check", action="store_true", help="skip the halved mesh rerun")
    o = a.parse_args()
    for b in P.SCHOTTKY_BENCHMARKS:
        print(f"[{b.name}] reference mesh", flush=True)
        rows = sweep(b, 1.0)
        mesh = None
        if not o.no_mesh_check:
            print(f"[{b.name}] halved mesh", flush=True)
            fine = sweep(b, 2.0)
            mesh = max(abs(x["current"] - y["current"]) / abs(y["current"]) for x, y in zip(rows, fine, strict=True))
            print(f"[{b.name}] mesh convergence {mesh:.3e}", flush=True)
        p = os.path.join(o.out, f"{b.name}.csv")
        write(b, rows, mesh, p)
        print(f"[{b.name}] wrote {p}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
